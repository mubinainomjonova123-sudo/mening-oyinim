let nickname = "";
let selectedAge = "";
let current = 0;
let score = 0;
let correct = 0;
let wrong = 0;
let seconds = 20;
let timerInterval = null;
let gameQuestions = [];
let answered = false;
let soundEnabled = true;

const $ = id => document.getElementById(id);

// Sahifalarni almashtirish
function showPage(page) {
    stopTimer();

    document.querySelectorAll(".page").forEach(p => {
        p.classList.remove("active");
    });

    $(page).classList.add("active");

    document.querySelectorAll(".nav-link").forEach(b => {
        b.classList.remove("active");
    });

    const index = {home:0, ranking:1, settings:2}[page];

    if (index !== undefined) {
        document.querySelectorAll(".nav-link")[index].classList.add("active");
    }

    if (page === "ranking") renderRanking();
}

// Yosh tanlash
document.querySelectorAll(".age-card").forEach(card => {
    card.addEventListener("click", () => {
        document.querySelectorAll(".age-card").forEach(c =>
            c.classList.remove("selected")
        );

        card.classList.add("selected");
        selectedAge = card.dataset.age;
        $("formError").textContent = "";
        playSound(500);
    });
});

// O'yinni boshlash
$("startBtn").addEventListener("click", () => {
    nickname = $("nickname").value.trim();

    if (!nickname) {
        $("formError").textContent = "⚠ Iltimos, ismingizni kiriting!";
        $("nickname").focus();
        return;
    }

    if (!selectedAge) {
        $("formError").textContent = "⚠ Yosh toifasini tanlang!";
        return;
    }

    startGame();
});

function startGame() {
    stopTimer();

    current = 0;
    score = 0;
    correct = 0;
    wrong = 0;

    gameQuestions = [...questionBank[selectedAge]]
        .sort(() => Math.random() - 0.5);

    $("gamePlayer").textContent = nickname;
    $("playerAvatar").textContent = nickname[0].toUpperCase();
    $("gameScore").textContent = "0";

    showPage("game");
    showQuestion();
}

// Savol chiqarish
function showQuestion() {
    stopTimer();

    answered = false;
    seconds = Number($("timeSetting").value);

    const q = gameQuestions[current];

    $("questionEmoji").textContent = q.e;
    $("category").textContent = "✦ " + q.c;
    $("questionText").textContent = q.q;

    $("questionCount").textContent =
        `SAVOL ${current + 1} / ${gameQuestions.length}`;

    const percent = ((current + 1) / gameQuestions.length) * 100;

    $("progressBar").style.width = percent + "%";
    $("progressPercent").textContent = Math.round(percent) + "%";

    $("answerFeedback").textContent = "";
    $("nextBtn").hidden = true;

    const grid = $("answerGrid");
    grid.innerHTML = "";

    q.a.forEach((answer, i) => {
        const button = document.createElement("button");

        button.className = "answer-btn";
        button.textContent = answer;

        button.addEventListener("click", () => checkAnswer(i, button));

        grid.appendChild(button);
    });

    updateTimer();
    timerInterval = setInterval(() => {
        seconds--;
        updateTimer();

        if (seconds <= 0) {
            stopTimer();
            if (!answered) checkAnswer(-1);
        }
    }, 1000);
}

function updateTimer() {
    $("timer").textContent = seconds;

    $("timer").style.color =
        seconds <= 5 ? "#ff657b" : "";
}

function stopTimer() {
    if (timerInterval) {
        clearInterval(timerInterval);
        timerInterval = null;
    }
}

// Ovoz effektlari
function playSound(frequency = 650) {
    if (!soundEnabled) return;

    try {
        const AudioContextClass =
            window.AudioContext || window.webkitAudioContext;

        if (!AudioContextClass) return;

        const context = new AudioContextClass();
        const oscillator = context.createOscillator();
        const gain = context.createGain();

        oscillator.frequency.value = frequency;
        oscillator.type = "sine";

        gain.gain.setValueAtTime(0.08, context.currentTime);
        gain.gain.exponentialRampToValueAtTime(
            0.001, context.currentTime + 0.2
        );

        oscillator.connect(gain);
        gain.connect(context.destination);

        oscillator.start();
        oscillator.stop(context.currentTime + 0.2);

        oscillator.onended = () => context.close();
    } catch (error) {
        console.log("Audio ishlamadi:", error);
    }
}

// Javobni tekshirish
function checkAnswer(index, clickedButton) {
    if (answered) return;

    answered = true;
    stopTimer();

    const q = gameQuestions[current];
    const buttons = document.querySelectorAll(".answer-btn");

    buttons.forEach(button => button.disabled = true);

    if (index === q.x) {
        clickedButton.classList.add("correct");

        correct++;

        const earned = 10 + Math.floor(seconds / 5);
        score += earned;

        $("answerFeedback").textContent =
            `✓ Ajoyib! To‘g‘ri javob! +${earned} XP`;

        $("answerFeedback").style.color = "#32e9a8";

        playSound(850);
    } else {
        if (clickedButton) {
            clickedButton.classList.add("wrong");
        }

        buttons[q.x].classList.add("correct");

        wrong++;

        $("answerFeedback").textContent =
            index === -1
            ? "⏰ Vaqt tugadi! To‘g‘ri javob: " + q.a[q.x]
            : "✕ Noto‘g‘ri! To‘g‘ri javob: " + q.a[q.x];

        $("answerFeedback").style.color = "#ff758a";

        playSound(250);
    }

    $("gameScore").textContent = score;
    $("nextBtn").hidden = false;
}

// Keyingi savol
$("nextBtn").addEventListener("click", () => {
    current++;

    if (current < gameQuestions.length) {
        showQuestion();
    } else {
        finishGame();
    }
});

// O'yinni yakunlash
function finishGame() {
    stopTimer();
    showPage("result");

    const total = gameQuestions.length;
    const accuracy = Math.round((correct / total) * 100);

    $("resultName").textContent = nickname;
    $("finalScore").textContent = score;
    $("correctCount").textContent = correct;
    $("wrongCount").textContent = wrong;
    $("accuracy").textContent = accuracy + "%";

    if (accuracy === 100) {
        $("resultMessage").textContent =
            "👑 Mukammal natija! Sen haqiqiy chempionsan!";
    } else if (accuracy >= 70) {
        $("resultMessage").textContent =
            "🔥 Juda yaxshi! Sen ajoyib bilimdonsan!";
    } else if (accuracy >= 40) {
        $("resultMessage").textContent =
            "💪 Yaxshi harakat! Yana bir bor urinib ko‘r!";
    } else {
        $("resultMessage").textContent =
            "🚀 Mashq qilishda davom et! Sen uddalaysan!";
    }

    saveResult();
    playSound(900);
}

// Natijalarni saqlash
function saveResult() {
    let history = JSON.parse(
        localStorage.getItem("aqlliRanking") || "[]"
    );

    history.push({
        name: nickname,
        age: selectedAge,
        score: score,
        correct: correct,
        date: new Date().toLocaleDateString("uz-UZ")
    });

    history.sort((a, b) => b.score - a.score);

    history = history.slice(0, 100);

    localStorage.setItem("aqlliRanking", JSON.stringify(history));
}

// Reyting
function renderRanking() {
    const history = JSON.parse(
        localStorage.getItem("aqlliRanking") || "[]"
    );

    const list = $("rankingList");
    list.innerHTML = "";

    if (history.length === 0) {
        list.innerHTML = `
            <div style="padding:30px;text-align:center;color:var(--muted)">
                🏆 Hozircha reyting bo‘sh. Birinchi chempion bo‘l!
            </div>
        `;
        return;
    }

    history.forEach((player, index) => {
        const row = document.createElement("div");
        row.className = "ranking-row";

        const number = document.createElement("strong");
        number.className = "rank-number";
        number.textContent = index + 1;

        const name = document.createElement("span");
        name.textContent = "👤 " + player.name;

        const age = document.createElement("span");
        age.textContent = player.age + " yosh";

        const points = document.createElement("strong");
        points.textContent = player.score + " XP";

        row.append(number, name, age, points);
        list.appendChild(row);
    });
}

// Qayta o'ynash
function playAgain() {
    startGame();
}

// O'yindan chiqish
function exitGame() {
    if (confirm("O‘yinni tark etmoqchimisiz? Natija saqlanmaydi.")) {
        showPage("home");
    }
}

// Tungi / kunduzgi rejim
function setTheme(isDark) {
    document.body.classList.toggle("light", !isDark);
    $("themeBtn").textContent = isDark ? "☀️" : "🌙";
    $("darkToggle").checked = isDark;

    localStorage.setItem("aqlliTheme", isDark ? "dark" : "light");
}

$("themeBtn").addEventListener("click", () => {
    setTheme(document.body.classList.contains("light"));
});

$("darkToggle").addEventListener("change", e => {
    setTheme(e.target.checked);
});

// Ovoz sozlamasi
$("soundToggle").addEventListener("change", e => {
    soundEnabled = e.target.checked;
    localStorage.setItem("aqlliSound", soundEnabled ? "on" : "off");
    if (soundEnabled) playSound(700);
});

// Reytingni tozalash
function clearRanking() {
    if (confirm("Barcha reyting natijalarini o‘chirmoqchimisiz?")) {
        localStorage.removeItem("aqlliRanking");
        renderRanking();
        alert("Reyting tozalandi!");
    }
}

// Saqlangan sozlamalarni tiklash
function loadSettings() {
    const theme = localStorage.getItem("aqlliTheme");
    setTheme(theme !== "light");

    const sound = localStorage.getItem("aqlliSound");
    soundEnabled = sound !== "off";
    $("soundToggle").checked = soundEnabled;
}

loadSettings();
